# Back-compat: the historic ``(slug, display_name)`` pairs used across templates
# and the sitemap builder.
TOP_CITIES: list[tuple[str, str]] = [(r[0], r[1]) for r in CITY_ROWS]

_BY_SLUG: dict[str, tuple] = {r[0]: r for r in CITY_ROWS}
_CITY_BY_SLUG: dict[str, str] = {r[0]: r[1] for r in CITY_ROWS}


def city_slugify(value: str) -> str:
    """URL-safe, accent-free slug for a city name."""
    if not value:
        return ""
    value = unicodedata.normalize("NFKD", value)
    value = value.encode("ascii", "ignore").decode("ascii")
    value = re.sub(r"[^\w\s-]", "", value).strip().lower()
    return re.sub(r"[-\s]+", "-", value).strip("-")


def city_display_name(slug: str) -> str:
    """Human-readable city name for a slug.

    Known cities keep their accented display name; unknown slugs are prettified
    (`aix-en-provence` -> `Aix En Provence`) so arbitrary city pages still render.
    """
    slug = (slug or "").strip().lower()
    if slug in _CITY_BY_SLUG:
        return _CITY_BY_SLUG[slug]
    parts = [p for p in slug.replace("_", "-").split("-") if p]
    return " ".join(p.capitalize() for p in parts)


def is_known_city(slug: str) -> bool:
    return (slug or "").strip().lower() in _BY_SLUG


def city_info(slug: str) -> dict | None:
    """Full record for a known city, or ``None``.

    Keys: ``slug, name, insee, postal_codes, dept_code, population, lat, lon``.
    """
    row = _BY_SLUG.get((slug or "").strip().lower())
    if row is None:
        return None
    return {
        "slug": row[0],
        "name": row[1],
        "insee": row[2],
        "postal_codes": list(row[3]),
        "dept_code": row[4],
        "population": row[5],
        "lat": row[6],
        "lon": row[7],
    }


def cities_in_department(dept_code: str) -> list[dict]:
    """Every known city of a department, largest first."""
    code = (dept_code or "").strip().lower()
    rows = [r for r in CITY_ROWS if r[4].lower() == code]
    rows.sort(key=lambda r: -r[5])
    return [city_info(r[0]) for r in rows]  # type: ignore[misc]


def _haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = math.radians(lat2 - lat1)
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def nearby_cities(slug: str, limit: int = 10, max_km: float = 60.0) -> list[dict]:
    """Real geographic neighbours, nearest first.

    Powers the internal-linking mesh:each city page links to the cities a visitor
    would actually consider next, which is both better UX and a far stronger
    crawl-path signal than an arbitrary fixed top-N list.
    """
    origin = city_info(slug)
    if origin is None:
        return []
    out: list[tuple[float, dict]] = []
    for row in CITY_ROWS:
        if row[0] == origin["slug"]:
            continue
        d = _haversine_km(origin["lat"], origin["lon"], row[6], row[7])
        if d <= max_km:
            info = city_info(row[0])
            if info is not None:
                info["distance_km"] = round(d)
                out.append((d, info))
    out.sort(key=lambda t: t[0])
    return [info for _, info in out[:limit]]
